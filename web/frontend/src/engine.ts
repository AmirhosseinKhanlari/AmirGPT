// Chooses where generation runs: on the Python server (/api/generate) or entirely in this browser
// (onnxruntime-web, WebGPU with a wasm fallback; see src/webgpu/). Both produce the same events.
import { useEffect, useState } from "react";
import type { DoneEvent, GenerateRequest, Tok } from "./api";
import { STATIC_SITE, streamGenerate } from "./api";
import { readPref, writePref } from "./prefs";

export type EngineKind = "server" | "browser";

/** Models that have an in-browser (ONNX) export. OpenAI GPT-2 is served by the Python server only. */
export const BROWSER_MODELS = new Set(["amirgpt-chat", "amirgpt-base"]);

export type EngineStatus = {
  kind: EngineKind;
  /** in-browser only: what is happening with the model download / session */
  phase?: "meta" | "download" | "verify" | "init" | "ready" | "error";
  model?: string;
  loaded?: number;
  total?: number;
  fromCache?: boolean;
  backend?: "webgpu" | "wasm";
  dtype?: string;
  fallbackReason?: string;
  error?: string;
};

let status: EngineStatus = { kind: STATIC_SITE ? "browser" : readPref<EngineKind>("amirgpt.engine", "server") };
const listeners = new Set<(s: EngineStatus) => void>();
function set(s: Partial<EngineStatus>) {
  status = { ...status, ...s };
  listeners.forEach((l) => l(status));
}

export function setEngine(kind: EngineKind) {
  if (STATIC_SITE) return; // the static site has no server engine
  writePref("amirgpt.engine", kind);
  set({ kind, phase: undefined, error: undefined });
}

export function useEngine(): EngineStatus {
  const [s, setS] = useState(status);
  useEffect(() => {
    listeners.add(setS);
    setS(status);
    return () => { listeners.delete(setS); };
  }, []);
  return s;
}

/** Same contract as api.ts streamGenerate, routed to the selected engine. */
export async function generate(req: GenerateRequest, onToken: (t: Tok) => void, signal: AbortSignal): Promise<DoneEvent> {
  if (status.kind === "server") return streamGenerate(req, onToken, signal);
  if (!BROWSER_MODELS.has(req.model)) {
    throw new Error(`${req.model} can only run on the server. Switch the engine to "Server" in Settings, or pick an AmirGPT model.`);
  }
  const wg = await import("./webgpu");
  // the static site ships only the fp16 exports (GitHub Pages size limit), served next to the page
  if (STATIC_SITE) wg.setModelBaseUrl(`${import.meta.env.BASE_URL}models`);
  try {
    const info = await wg.loadModel(req.model, (p) =>
      set({ phase: p.phase, model: req.model, loaded: p.loaded, total: p.total, fromCache: p.fromCache, backend: p.backend, error: undefined }),
      STATIC_SITE ? { dtype: "fp16" } : undefined);
    set({ phase: "ready", model: req.model, backend: info.backend, dtype: info.dtype, fallbackReason: info.fallbackReason });
  } catch (e) {
    set({ phase: "error", model: req.model, error: String((e as Error)?.message ?? e) });
    throw e;
  }
  return wg.streamGenerateLocal(req, onToken, signal);
}

/** One-line description of the in-browser engine state, for the settings panel. */
export function describeStatus(s: EngineStatus): string {
  if (s.kind === "server") return "Tokens are generated by the Python server.";
  const mb = (b?: number) => ((b ?? 0) / 1e6).toFixed(0);
  switch (s.phase) {
    case undefined: return "The model downloads on your first message (about 250 MB, cached afterwards).";
    case "meta": return "Preparing download…";
    case "download": return s.fromCache ? "Loading model from browser cache…" : `Downloading model: ${mb(s.loaded)} / ${mb(s.total)} MB`;
    case "verify": return "Checking download…";
    case "init": return "Starting the model on your GPU…";
    case "ready": return `Running in your browser on ${s.backend === "webgpu" ? "WebGPU" : "WebAssembly (CPU)"}${s.dtype ? `, ${s.dtype}` : ""}.${s.fallbackReason ? ` (${s.fallbackReason})` : ""}`;
    case "error": return `Could not start the in-browser model: ${s.error}`;
  }
}
