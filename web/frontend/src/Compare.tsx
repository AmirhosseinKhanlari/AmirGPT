// Compare tab: one prompt, 2-3 models side by side, same sampling parameters and the same seed.
// Columns stream in parallel; each uses the same token view (lens, token card, fork, river).
import { useEffect, useRef, useState } from "react";
import type { Alt, DoneEvent, GenParams, ModelInfo, Tok } from "./api";
import { HttpError } from "./api";
import { generate } from "./engine";
import { readPref, writePref } from "./prefs";
import { meanProb, perplexity, TokenView } from "./tokens";
import { uid } from "./tree";

type Column = {
  key: string; // changes on every (re)start, so late events from an aborted stream are ignored
  model: string;
  tokens: Tok[];
  tail: string;
  streaming: boolean;
  prefixLen: number; // forced tokens at the start (fork), not generated by this stream
  startedAt: number;
  endedAt?: number;
  done?: DoneEvent;
  error?: string;
  stopped?: boolean;
  fork?: { at: number };
};
type RunSpec = { prompt: string; params: GenParams }; // params.seed is always concrete here

const MIN_COLS = 2, MAX_COLS = 3;

const newColumn = (model: string, prefix: Tok[] = []): Column => ({
  key: uid(), model, tokens: prefix, tail: "", streaming: true, prefixLen: prefix.length, startedAt: performance.now(),
});

export function Compare({ models, params, lens, markdown, hidden, onOpenSettings }: {
  models: ModelInfo[]; params: GenParams; lens: boolean; markdown: boolean; hidden: boolean; onOpenSettings: () => void;
}) {
  const [prompt, setPrompt] = useState("");
  const [picked, setPicked] = useState<string[] | null>(() => readPref<string[] | null>("amirgpt.compare.models", null));
  const [cols, setCols] = useState<Column[]>([]);
  const [spec, setSpec] = useState<RunSpec | null>(null);
  const ctrls = useRef(new Map<string, AbortController>());

  useEffect(() => writePref("amirgpt.compare.models", picked), [picked]);
  useEffect(() => () => { for (const c of ctrls.current.values()) c.abort(); }, []);

  // default: every model (up to 3), in the backend's order
  const ids = models.map((m) => m.id);
  const selected = (picked ?? ids).filter((id) => ids.includes(id)).slice(0, MAX_COLS);
  const busy = cols.some((c) => c.streaming);

  const toggle = (id: string) => {
    const on = selected.includes(id);
    if (on && selected.length <= MIN_COLS) return;
    if (!on && selected.length >= MAX_COLS) return;
    setPicked(on ? selected.filter((x) => x !== id) : ids.filter((x) => x === id || selected.includes(x)));
  };

  const patch = (key: string, f: (c: Column) => Column) => setCols((cs) => cs.map((c) => (c.key === key ? f(c) : c)));

  const stream = async (col: Column, run: RunSpec) => {
    const info = models.find((m) => m.id === col.model);
    const ctrl = new AbortController();
    ctrls.current.set(col.key, ctrl);
    let pending: Tok[] = [];
    let raf = 0;
    const flush = () => {
      raf = 0;
      if (!pending.length) return;
      const add = pending;
      pending = [];
      patch(col.key, (c) => ({ ...c, tokens: [...c.tokens, ...add] }));
    };
    try {
      const done = await generate({
        model: col.model,
        ...(info?.mode === "complete" ? { prompt: run.prompt } : { messages: [{ role: "user", content: run.prompt }] }),
        prefix_ids: col.tokens.map((t) => t.id),
        params: run.params,
      }, (t) => {
        pending.push(t);
        if (!raf) raf = requestAnimationFrame(flush);
      }, ctrl.signal);
      if (raf) cancelAnimationFrame(raf);
      flush();
      patch(col.key, (c) => ({ ...c, streaming: false, done, tail: done.tail, endedAt: performance.now() }));
    } catch (e) {
      if (raf) cancelAnimationFrame(raf);
      flush();
      const err = e as Error;
      const aborted = err.name === "AbortError";
      const msg = aborted ? undefined
        : err instanceof HttpError && err.status === 409 ? `Model unavailable (HTTP 409): ${err.message}`
        : err instanceof HttpError ? `Request failed (HTTP ${err.status}): ${err.message}`
        : `Request failed: ${err.message}`;
      patch(col.key, (c) => ({ ...c, streaming: false, stopped: aborted, error: msg, endedAt: performance.now() }));
    } finally {
      if (ctrls.current.get(col.key) === ctrl) ctrls.current.delete(col.key);
    }
  };

  const stopAll = () => { for (const c of ctrls.current.values()) c.abort(); };
  const stopOne = (key: string) => ctrls.current.get(key)?.abort();

  const run = () => {
    if (!prompt.trim() || busy || selected.length < MIN_COLS) return;
    stopAll();
    // one seed for every column: the chosen one, or a random one drawn once for this run
    const seed = params.seed ?? Math.floor(Math.random() * 2 ** 31);
    const next: RunSpec = { prompt, params: { ...params, seed } };
    const fresh = selected.map((id) => newColumn(id));
    setSpec(next);
    setCols(fresh);
    for (const c of fresh) void stream(c, next);
  };

  const fork = (col: Column, i: number, alt: Alt) => {
    if (!spec) return;
    const orig = col.tokens[i];
    const forced: Tok = { id: alt.id, text: alt.text, prob: alt.prob, alternatives: orig.alternatives };
    stopOne(col.key);
    const nc = { ...newColumn(col.model, [...col.tokens.slice(0, i), forced]), fork: { at: i } };
    setCols((cs) => cs.map((c) => (c.key === col.key ? nc : c)));
    void stream(nc, spec);
  };

  const p = params;
  return (
    <div className="compare" hidden={hidden}>
      <div className="compare-inner">
        <header className="cmp-head">
          <h2>Compare</h2>
          <p className="muted">One prompt, the same sampling settings and the same seed for every model. Chat models get it as a
            user message; completion models continue it as text.</p>
        </header>
        <form className="cmp-form" onSubmit={(e) => { e.preventDefault(); run(); }}>
          <div className="cmp-models" role="group" aria-label="Models to compare (2 or 3)">
            {models.map((m) => {
              const on = selected.includes(m.id);
              const locked = (on && selected.length <= MIN_COLS) || (!on && selected.length >= MAX_COLS);
              return (
                <label key={m.id} className={"cmp-chip" + (on ? " on" : "") + (locked || busy ? " locked" : "")}
                       title={locked ? (on ? "Compare needs at least 2 models" : "At most 3 models") : m.description}>
                  <input type="checkbox" checked={on} disabled={locked || busy} onChange={() => toggle(m.id)} />
                  <span className="cmp-check" aria-hidden>{on ? "✓" : ""}</span>
                  <span className="model-name">{m.name}</span>
                  <span className="model-tag">{!m.available ? "unavailable" : m.mode === "chat" ? "chat" : "completion"}</span>
                </label>
              );
            })}
          </div>
          <textarea value={prompt} rows={Math.min(6, Math.max(2, prompt.split("\n").length))}
                    placeholder="A prompt for every model, e.g. “Give me three tips for studying.”"
                    onChange={(e) => setPrompt(e.target.value)}
                    onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) { e.preventDefault(); run(); } }} />
          <div className="cmp-actions">
            <button type="button" className="cmp-params" onClick={onOpenSettings} title="Edit sampling settings">
              <span>T {p.temperature.toFixed(2)}</span><span>top-k {p.top_k}</span><span>top-p {p.top_p.toFixed(2)}</span>
              <span>rep {p.repetition_penalty.toFixed(2)}</span><span>max {p.max_new_tokens}</span>
              <span>seed {p.seed ?? "random"}</span><b>edit</b>
            </button>
            {/* distinct keys: React must not morph the clicked Stop button into the submit button
                during the click, or the browser would submit the form (start a new run) right after Stop */}
            {busy ? <button key="stop" type="button" className="btn" onClick={stopAll}>Stop</button>
                  : <button key="run" type="submit" className="btn primary" disabled={!prompt.trim() || selected.length < MIN_COLS}>Compare</button>}
          </div>
        </form>

        {spec && (
          <p className="cmp-runinfo muted small">
            Ran with seed <b className="mono">{spec.params.seed}</b>{params.seed === null ? " (drawn at random for this run)" : ""}, the same for
            every column. Hover or tap a token to see the alternatives; picking one forks that column from there.
          </p>
        )}
        {cols.length > 0 && (
          <div className={`cmp-grid cols-${cols.length}`}>
            {cols.map((c) => {
              const info = models.find((m) => m.id === c.model);
              return <CompareColumn key={c.key} col={c} info={info} prompt={spec?.prompt ?? ""} lens={lens} markdown={markdown}
                                    onFork={(i, alt) => fork(c, i, alt)} onStop={() => stopOne(c.key)} />;
            })}
          </div>
        )}
      </div>
    </div>
  );
}

function CompareColumn({ col, info, prompt, lens, markdown, onFork, onStop }: {
  col: Column; info?: ModelInfo; prompt: string; lens: boolean; markdown: boolean;
  onFork: (i: number, alt: Alt) => void; onStop: () => void;
}) {
  const generated = col.tokens.length - col.prefixLen;
  const secs = ((col.endedAt ?? performance.now()) - col.startedAt) / 1000;
  const tps = col.done ? col.done.tokens_per_sec : secs > 0.05 && generated > 0 ? generated / secs : null;
  const mp = meanProb(col.tokens);
  const ppl = perplexity(col.tokens);
  const status = col.streaming ? "generating…" : col.error ? "error" : col.stopped ? "stopped"
    : col.done?.reason === "length" ? "hit length limit" : "finished";
  const complete = info?.mode === "complete";
  return (
    <section className={"cmp-col" + (col.error ? " has-error" : "")} aria-label={info?.name ?? col.model} aria-busy={col.streaming}>
      <header className="cmp-col-head">
        <b>{info?.name ?? col.model}</b>
        <span className="model-tag">{complete ? "completion" : "chat"}</span>
        <span className={"cmp-status" + (col.streaming ? " live" : "")}>{status}</span>
        {col.streaming && <button className="link" onClick={onStop}>stop</button>}
      </header>
      <div className="cmp-col-body">
        {complete && <div className="cmp-prompt" title="completion models continue the prompt">{prompt}</div>}
        <TokenView className="tokens cmp-tokens" tokens={col.tokens} tail={col.tail} lens={lens} markdown={markdown}
                   interactive={!col.streaming} streaming={col.streaming} forkAt={col.fork?.at} error={col.error}
                   onFork={onFork} empty={col.stopped ? <span className="muted">(stopped before the first token)</span> : undefined} />
      </div>
      <footer className="cmp-stats" title="tokens · speed · mean probability of the sampled tokens · perplexity">
        <span><b>{col.tokens.length}</b> tok</span>
        <span><b>{tps !== null ? tps.toFixed(0) : "–"}</b> tok/s</span>
        <span>mean p <b>{mp !== null ? (mp * 100).toFixed(1) + "%" : "–"}</b></span>
        <span>ppl <b>{ppl !== null ? ppl.toFixed(1) : "–"}</b></span>
        {col.fork && <span className="chip" title="this column was forked from a token you picked">forked at token {col.fork.at + 1}</span>}
      </footer>
    </section>
  );
}
